/**
 * Windows variant of `Icon.ts` — see its header comment for what this
 * module is and why every consumer imports icons through it instead of
 * `lucide-react-native/icons/*` directly.
 *
 * `react-native-svg`'s own Windows native module (the thing every
 * `lucide-react-native` icon renders through) doesn't currently build on
 * this app's Fabric/New-Architecture toolchain — see the confirmed,
 * open upstream issue at
 * https://github.com/software-mansion/react-native-svg/issues/2745.
 * Rather than depend on it at all here, every icon in this file is
 * rendered through React Native for Windows's own native SVG support
 * instead: RN core's `Image` component recognizes an SVG payload (via
 * WinUI's `SvgImageSource` under the hood) and rasterizes it directly, no
 * extra native module required. Each exported icon builds a standalone
 * SVG XML string from Lucide's own `iconNode` data (the same
 * `[tag, attrs]` array every `lucide-react-native` icon is generated
 * from) plus this call's `color`/`size`/`strokeWidth`, and hands it to
 * `Image` as a percent-encoded `data:image/svg+xml,...` URI.
 *
 * This only supports the narrow prop surface every icon in this package
 * actually uses (`color`, `size`, `strokeWidth`) — not
 * `lucide-react-native`'s full SVG-prop passthrough, which nothing here
 * relies on.
 *
 * Generated from the exact `iconNode` data baked into the installed
 * `lucide-react-native`; regenerate by re-running the same extraction
 * against `node_modules/lucide-react-native/dist/esm/icons/*.mjs` if the
 * set of icons this package uses ever changes.
 *
 * @module @noteferry/ui/Icon
 *
 * @file      Icon.windows.tsx
 * @author    Gage Sorrell <gage@sorrell.sh>
 * @copyright (c) 2026 Gage Sorrell
 * @license   MIT
 */

import * as React from "react";
// Aliased: one of this file's own exported icons is named `Image` (from
// Lucide's "image" icon) and would otherwise collide with this import.
import { Image as RNImage, type ImageStyle, type StyleProp } from "react-native";
import { EncodeSvgDataUri } from "./Utility/index.js";

type IconShapeAttrs = Readonly<Record<string, string>>;
type IconShape = readonly [ Tag: string, Attrs: IconShapeAttrs ];

/** One Lucide icon's shape list — the same `iconNode` format `lucide-react-native` itself is generated from. */
export type IconNode = readonly IconShape[];

/** {@inheritDoc Icon} */
export interface LucideIconProps
{
    readonly color?: string;
    readonly size?: number;
    readonly strokeWidth?: number;
    readonly style?: StyleProp<ImageStyle>;
}

const EscapeXmlAttribute = (Value: string): string =>
    Value
        .replace(/&/g, "&amp;")
        .replace(/"/g, "&quot;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;");

/**
 * Builds one standalone SVG shape tag, merging Lucide's own default
 * per-shape styling (`fill="none"`, themed `stroke`/`stroke-width`,
 * rounded caps/joins) underneath that shape's own `iconNode` attributes —
 * mirroring `lucide-react-native`'s own `Icon` component
 * (`{ ...childDefaultAttributes, ...customAttrs, ...attrs }`). A shape
 * that hardcodes `fill: "currentColor"` (Lucide's convention for a filled
 * accent dot) resolves against the same `Color` used for the stroke,
 * since a data-URI image has no CSS `currentColor` context to inherit.
 */
const BuildShapeMarkup = (
    [ Tag, Attrs ]: IconShape,
    Color: string,
    StrokeWidth: number
): string =>
{
    const Merged: Record<string, string> = {
        fill: "none",
        stroke: Color,
        "stroke-linecap": "round",
        "stroke-linejoin": "round",
        "stroke-width": String(StrokeWidth),
        ...Attrs
    };
    delete Merged[ "key" ];

    const AttrString = Object.entries(Merged)
        .map(([ Key, Value ]) =>
            `${ Key }="${ EscapeXmlAttribute(Value === "currentColor" ? Color : Value) }"`)
        .join(" ");

    return `<${ Tag } ${ AttrString }/>`;
};

const BuildSvgDataUri = (Node: IconNode, Color: string, StrokeWidth: number): string =>
{
    const Shapes = Node.map((Shape: IconShape) => BuildShapeMarkup(Shape, Color, StrokeWidth)).join("");
    const Svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">${ Shapes }</svg>`;

    return EncodeSvgDataUri(Svg);
};

const RenderLucideIcon = ({
    Node,
    color = "#000000",
    size = 24,
    strokeWidth = 2,
    style
}: LucideIconProps & { readonly Node: IconNode }): React.JSX.Element =>
{
    const Uri = React.useMemo(
        () => BuildSvgDataUri(Node, color, strokeWidth),
        [ Node, color, strokeWidth ]
    );

    return (
        <RNImage
            source={ { uri: Uri } }
            style={ [ { height: size, width: size }, style ] }
        />
    );
};

/**
 * Builds one icon's exported component, once, at module load — mirroring
 * `lucide-react-native`'s own `createLucideIcon` factory. `Node` is
 * captured in closure rather than passed as a fresh inline literal on every
 * render, so `RenderLucideIcon`'s `useMemo` above actually memoizes
 * across re-renders instead of recomputing on every one.
 */
const CreateLucideIcon = (Node: IconNode) =>
    (Props: LucideIconProps): React.JSX.Element => <RenderLucideIcon Node={ Node } { ...Props } />;

